import { useState } from 'react'
import {
  AlertCircle, CheckCircle2, Clock3, Download,
  Flame, Image as ImageIcon, Layers3, ScanLine, ShieldCheck,
  Wind,
} from 'lucide-react'
import type { PredictionRecord } from '../types/api'

type ResultPanelProps = {
  record: PredictionRecord
}

type ImageTab = 'original' | 'overlay' | 'fire' | 'smoke'

export default function ResultPanel({ record }: ResultPanelProps) {
  const [activeTab, setActiveTab] = useState<ImageTab>('overlay')
  const { response } = record

  const images: Record<ImageTab, { label: string; url: string }> = {
    original: {
      label: 'Original image',
      url: record.originalImage,
    },
    overlay: {
      label: 'Segmentation overlay',
      url: `/api/v1/results/${response.result_id}/overlay`,
    },
    fire: {
      label: 'Fire mask',
      url: `/api/v1/results/${response.result_id}/fire-mask`,
    },
    smoke: {
      label: 'Smoke mask',
      url: `/api/v1/results/${response.result_id}/smoke-mask`,
    },
  }

  const fire = response.classes.fire
  const smoke = response.classes.smoke

  return (
    <section className="result-workspace">
      <div className="result-heading">
        <div>
          <div className="eyebrow"><span className="eyebrow-line" /> ANALYSIS OUTPUT</div>
          <h2>Segmentation results</h2>
          <p>Actual output generated by {response.model === 'unet' ? 'U-Net' : 'YOLO11-seg'}.</p>
        </div>
        <span className="result-success"><CheckCircle2 size={15} /> Completed</span>
      </div>

      <div className="result-layout">
        <article className="panel result-image-panel">
          <div className="result-tabs">
            {(Object.keys(images) as ImageTab[]).map((key) => (
              <button
                key={key}
                className={`result-tab ${activeTab === key ? 'active' : ''}`}
                onClick={() => setActiveTab(key)}
              >
                {images[key].label}
              </button>
            ))}
          </div>

          <div className="result-image-frame">
            <img
              src={images[activeTab].url}
              alt={images[activeTab].label}
              key={images[activeTab].url}
            />
          </div>

          <div className="result-image-footer">
            <span><ImageIcon size={14} /> {record.fileName}</span>
            <a
              href={images[activeTab].url}
              download={`${response.result_id}-${activeTab}.png`}
              target="_blank"
              rel="noreferrer"
            >
              <Download size={14} /> Download image
            </a>
          </div>
        </article>

        <div className="result-side">
          <article className="panel result-info-card">
            <div className="eyebrow">PREDICTION DETAILS</div>
            <div className="result-model-name">
              <ScanLine size={19} />
              <strong>{response.model === 'unet' ? 'U-Net' : 'YOLO11-seg'}</strong>
            </div>
            <div className="result-detail-row">
              <span><Clock3 size={14} /> Inference time</span>
              <strong>{response.processing_time_seconds.toFixed(4)} s</strong>
            </div>
            <div className="result-detail-row">
              <span><Layers3 size={14} /> Image dimensions</span>
              <strong>{response.image.width} × {response.image.height}</strong>
            </div>
            <div className="result-detail-row">
              <span><ShieldCheck size={14} /> Result ID</span>
              <strong className="result-id">{response.result_id.slice(0, 12)}…</strong>
            </div>
          </article>

          <article className="panel class-result-card">
            <div className="class-result-title">
              <Flame size={17} />
              <strong>Fire segmentation</strong>
              <span className={fire.detected ? 'detected' : 'not-detected'}>
                {fire.detected ? 'Detected' : 'Not detected'}
              </span>
            </div>
            <div className="coverage-number">{fire.coverage_percent.toFixed(4)}<small>%</small></div>
            <div className="coverage-track">
              <div className="coverage-fill fire-fill" style={{ width: `${Math.min(fire.coverage_percent, 100)}%` }} />
            </div>
            <div className="coverage-caption">{fire.pixel_count.toLocaleString()} fire pixels</div>
          </article>

          <article className="panel class-result-card">
            <div className="class-result-title smoke-title">
              <Wind size={17} />
              <strong>Smoke segmentation</strong>
              <span className={smoke.detected ? 'detected' : 'not-detected'}>
                {smoke.detected ? 'Detected' : 'Not detected'}
              </span>
            </div>
            <div className="coverage-number">{smoke.coverage_percent.toFixed(4)}<small>%</small></div>
            <div className="coverage-track">
              <div className="coverage-fill smoke-fill" style={{ width: `${Math.min(smoke.coverage_percent, 100)}%` }} />
            </div>
            <div className="coverage-caption">{smoke.pixel_count.toLocaleString()} smoke pixels</div>
          </article>
        </div>
      </div>

      <div className="result-disclaimer">
        <AlertCircle size={15} />
        Model segmentation output is an AI-generated analysis, not a confirmed real-world fire alarm.
      </div>
    </section>
  )
}

